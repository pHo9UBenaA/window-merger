import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { object, strings, text } from './lib/input.ts';
import { PROJECT_ROOT } from './lib/project-root.ts';

type Executable = {
	readonly file: string;
	readonly read: readonly string[];
	readonly write: readonly string[];
	readonly childProcess: boolean;
	readonly launcher: boolean;
};
type CommandConfig = {
	readonly executables: Readonly<Record<string, Executable>>;
	readonly packageScripts: Readonly<Record<string, string>>;
};

export const parseConfig = (input: unknown): CommandConfig => {
	const config = object(input);
	const executables = Object.fromEntries(
		Object.entries(object(config.executables)).map(([name, value]) => {
			if (!/^[a-zA-Z]\w*$/.test(name)) throw new Error(`Invalid command name: ${name}`);
			const entry = object(value);
			const file = text(entry.file);
			if (!/^(?:[a-z-]+\/)?[a-z-]+\.ts$/.test(file))
				throw new Error(`Invalid executable path: ${file}`);
			if (entry.childProcess !== undefined && typeof entry.childProcess !== 'boolean')
				throw new Error('Invalid child-process permission');
			if (entry.launcher !== undefined && typeof entry.launcher !== 'boolean')
				throw new Error('Invalid launcher setting');
			const read = strings(entry.read ?? []);
			const write = strings(entry.write ?? []);
			for (const path of [...read, ...write]) {
				if (path !== '$githubEnv') pathExpression(path);
			}
			return [
				name,
				{
					file,
					read,
					write,
					childProcess: entry.childProcess === true,
					launcher: entry.launcher === true,
				},
			];
		})
	);
	const packageScripts = Object.fromEntries(
		Object.entries(object(config.packageScripts)).map(([name, value]) => [name, text(value)])
	);
	return { executables, packageScripts };
};

const quote = (value: string): string =>
	`'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
const pathExpression = (path: string): string => {
	if (!/^[\w$./*-]+$/.test(path)) throw new Error(`Invalid permission path: ${path}`);
	const bases: Readonly<Record<string, string>> = {
		$code: 'PROJECT_ROOT',
		$tmp: 'tmpdir()',
		$runnerTemp: 'process.env.RUNNER_TEMP ?? tmpdir()',
	};
	const [prefix, ...parts] = path.split('/');
	const base = Object.hasOwn(bases, prefix) ? bases[prefix] : undefined;
	if (base) return parts.length ? `join(${base}, ${quote(parts.join('/'))})` : base;
	if (path.startsWith('$')) throw new Error(`Unknown permission path: ${path}`);
	if (path.startsWith('/') || path.split('/').includes('..'))
		throw new Error(`Invalid permission path: ${path}`);
	return `join(root, ${quote(path)})`;
};

const permissionExpressions = (entry: Executable): string[] => {
	const grants: string[] = [];
	for (const [kind, paths] of [
		['read', entry.read],
		['write', entry.write],
	] as const) {
		for (const path of paths) {
			if (path === '$githubEnv') {
				grants.push(
					`...(process.env.GITHUB_ENV\n\t\t? [\`--allow-fs-${kind}=\${resolve(root, process.env.GITHUB_ENV)}\`]\n\t\t: []),`
				);
			} else grants.push(`\`--allow-fs-${kind}=\${${pathExpression(path)}}\`,`);
		}
	}
	return grants;
};

const renderCommandModule = (
	entries: readonly (readonly [string, Executable])[],
	directory: string
): string => {
	const paths = entries.flatMap(([, entry]) => [...entry.read, ...entry.write]);
	const imports = [
		...(paths.some((path) => path.startsWith('$tmp') || path.startsWith('$runnerTemp'))
			? ["import { tmpdir } from 'node:os';"]
			: []),
		`import { ${paths.includes('$githubEnv') ? 'join, resolve' : 'join'} } from 'node:path';`,
		`import { PROJECT_ROOT } from ${quote(directory === 'lib' ? './project-root.ts' : '../lib/project-root.ts')};`,
	];
	const commands = entries.map(([name, entry]) =>
		[
			`export const ${name}Command = (root = process.cwd()): string[] => {`,
			`\tconst flags = [`,
			`\t\t'--permission',`,
			`\t\t\`--allow-fs-read=\${join(PROJECT_ROOT, 'package.json')}\`,`,
			`\t\t\`--allow-fs-read=\${join(PROJECT_ROOT, 'scripts')}\`,`,
			`\t\t\`--allow-fs-read=\${join(root, 'package.json')}\`,`,
			...permissionExpressions(entry).map((line) => `\t\t${line.replaceAll('\n', '\n\t')}`),
			`\t\t${quote(entry.childProcess ? '--allow-child-process' : '--no-allow-child-process')},`,
			`\t];`,
			`\treturn [...new Set(flags), join(PROJECT_ROOT, ${quote(`scripts/${entry.file}`)})];`,
			'};',
		].join('\n')
	);
	return `// Generated by scripts/generate-commands.ts; edit scripts/commands.json instead.\n${imports.join('\n')}\n\n${commands.join('\n\n')}\n`;
};

export const shellCommand = (entry: Executable): string => {
	const flags = ['--permission', '--allow-fs-read=./package.json', '--allow-fs-read=./scripts'];
	for (const [kind, paths] of [
		['read', entry.read],
		['write', entry.write],
	] as const) {
		for (const path of paths) {
			if (path.startsWith('$') && !path.startsWith('$code/'))
				throw new Error('Dynamic paths require a dedicated command script');
			flags.push(`--allow-fs-${kind}=./${path.replace(/^\$code\//, '')}`);
		}
	}
	flags.push(entry.childProcess ? '--allow-child-process' : '--no-allow-child-process');
	return ['node', ...new Set(flags), `./scripts/${entry.file}`].join(' ');
};

export const generateFiles = (
	config: CommandConfig,
	packageJson: string
): ReadonlyMap<string, string> => {
	const groups = new Map<string, (readonly [string, Executable])[]>();
	for (const entry of Object.entries(config.executables)) {
		const directory = dirname(entry[1].file);
		if (directory === '.' || !entry[1].launcher) continue;
		const entries = groups.get(directory) ?? [];
		entries.push(entry);
		groups.set(directory, entries);
	}
	const scripts = Object.fromEntries(
		Object.entries(config.packageScripts).map(([name, template]) => [
			name,
			template.replace(/\{\{(\w+)\}\}/g, (_, command: string) => {
				const entry = config.executables[command];
				if (!Object.hasOwn(config.executables, command))
					throw new Error(`Unknown executable: ${command}`);
				return shellCommand(entry);
			}),
		])
	);
	const pkg = object(JSON.parse(packageJson));
	return new Map([
		['package.json', `${JSON.stringify({ ...pkg, scripts }, null, '\t')}\n`],
		...[...groups].map(([directory, entries]): [string, string] => [
			`scripts/${directory}/commands.generated.ts`,
			renderCommandModule(entries, directory),
		]),
	]);
};

if (import.meta.main) {
	const config = parseConfig(
		JSON.parse(await readFile(join(PROJECT_ROOT, 'scripts/commands.json'), 'utf8'))
	);
	const outputs = generateFiles(
		config,
		await readFile(join(PROJECT_ROOT, 'package.json'), 'utf8')
	);
	for (const directory of await readdir(join(PROJECT_ROOT, 'scripts'), { withFileTypes: true })) {
		if (!directory.isDirectory()) continue;
		const path = `scripts/${directory.name}/commands.generated.ts`;
		if (
			!outputs.has(path) &&
			(await readdir(join(PROJECT_ROOT, 'scripts', directory.name))).includes(
				'commands.generated.ts'
			)
		)
			throw new Error(`${path} is obsolete; remove it`);
	}
	for (const [path, content] of outputs) {
		const destination = join(PROJECT_ROOT, path);
		if (process.argv.includes('--check')) {
			const current = await readFile(destination, 'utf8').catch(() => '');
			if (current.replaceAll('\r\n', '\n') !== content)
				throw new Error(`${path} is stale; run pnpm scripts:generate`);
		} else await writeFile(destination, content);
	}
}
